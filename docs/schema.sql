-- Архитектура предметных таблиц (справочный SQL).
-- Для установки приложения используйте manage.py migrate:
-- миграции создадут также пользователей, сессии и JWT blacklist.
CREATE TABLE bank_client (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(150) NOT NULL,
    iin varchar(12) UNIQUE NOT NULL,
    phone varchar(20) NOT NULL,
    email varchar(254) NOT NULL,
    created_at timestamptz NOT NULL
);
CREATE TABLE bank_account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL REFERENCES bank_client(id) DEFERRABLE INITIALLY DEFERRED,
    number varchar(20) UNIQUE NOT NULL,
    currency varchar(3) NOT NULL,
    balance numeric(16,2) NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT non_negative_balance CHECK (balance >= 0)
);
CREATE INDEX bank_account_client_id_idx ON bank_account(client_id);
-- Вывод связанной таблицы для преподавателя:
SELECT c.id, c.full_name, c.iin, a.number, a.currency, a.balance
FROM bank_client c LEFT JOIN bank_account a ON a.client_id=c.id
ORDER BY c.id, a.id;
-- Regex ИИН/номера и enum валюты проверяет сериализатор модели.
